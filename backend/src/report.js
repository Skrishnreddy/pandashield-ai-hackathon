// Report generation: Markdown for humans, SARIF 2.1.0 for tools (GitHub
// code scanning, IDEs).

const SEV_ICON = { critical: '🟥', high: '🟧', medium: '🟨', low: '🟦', info: '⬜' };

export function markdownReport(scan) {
  const s = scan.stats || {};
  const sev = s.bySeverity || {};
  const lines = [];
  lines.push(`# PandaShield AI Security Report`);
  lines.push('');
  lines.push(`**Scan:** ${scan.name}  `);
  lines.push(`**Source:** ${describeSource(scan.source)}  `);
  lines.push(`**Created:** ${scan.createdAt || 'n/a'}  `);
  lines.push(`**Security score:** ${s.securityScore ?? 'n/a'}/100  `);
  lines.push(`**Files scanned:** ${scan.meta?.filesScanned ?? 'n/a'} · **Dependencies checked:** ${scan.meta?.dependenciesChecked ?? 'n/a'}`);
  lines.push('');
  lines.push(`| Critical | High | Medium | Low |`);
  lines.push(`|---|---|---|---|`);
  lines.push(`| ${sev.critical || 0} | ${sev.high || 0} | ${sev.medium || 0} | ${sev.low || 0} |`);
  lines.push('');
  if (scan.ai?.executiveSummary) {
    lines.push(`## Executive summary (Gemini ${scan.ai.model || ''})`);
    lines.push('');
    lines.push(scan.ai.executiveSummary);
    lines.push('');
  }
  const byId = new Map((scan.findings || []).map((f) => [f.id, f]));
  if (scan.ai?.fixFirst?.length) {
    lines.push('## Fix first');
    lines.push('');
    scan.ai.fixFirst.forEach((id, i) => {
      const f = byId.get(id);
      if (f) lines.push(`${i + 1}. ${f.title} (${location(f)})`);
    });
    lines.push('');
  }
  lines.push('## Findings');
  lines.push('');
  for (const f of scan.findings || []) {
    lines.push(`### ${SEV_ICON[f.severity] || ''} ${f.title}`);
    lines.push('');
    lines.push(`- **Severity:** ${f.severity}${f.ai?.contextualSeverity && f.ai.contextualSeverity !== f.severity ? ` (Gemini contextual: ${f.ai.contextualSeverity})` : ''}${f.ai?.priority ? ` · **Priority:** ${f.ai.priority}` : ''}`);
    lines.push(`- **Location:** \`${location(f)}\``);
    lines.push(`- **Status:** ${f.status || 'open'}`);
    if (f.cwe) lines.push(`- **CWE:** ${f.cwe}`);
    if (f.owasp) lines.push(`- **OWASP:** ${f.owasp}`);
    if (f.advisory) lines.push(`- **Advisory:** [${f.advisory.id}](${f.advisory.url})${f.advisory.cve ? ` (${f.advisory.cve})` : ''}${f.advisory.fixedIn?.length ? ` · fixed in ${f.advisory.fixedIn.join(', ')}` : ''}`);
    lines.push('');
    if (f.ai?.explanation) {
      lines.push(f.ai.explanation);
      lines.push('');
      if (f.ai.attackScenario) lines.push(`**Attack scenario:** ${f.ai.attackScenario}`, '');
      if (f.ai.remediation) lines.push(`**Remediation:**`, '', f.ai.remediation, '');
      if (f.ai.fixedCode) lines.push('**Suggested fix:**', '', '```', f.ai.fixedCode, '```', '');
    } else {
      lines.push(f.description || '');
      lines.push('');
    }
  }
  lines.push('---');
  lines.push('_Generated by PandaShield AI — Hackathon Edition. Findings come from deterministic scanners (PandaShield SAST, secret detection, OSV.dev); explanations and prioritisation are generated by Gemini and should be reviewed by a developer._');
  return lines.join('\n');
}

export function sarifReport(scan) {
  const rules = new Map();
  for (const f of scan.findings || []) {
    if (!rules.has(f.ruleId)) {
      rules.set(f.ruleId, {
        id: f.ruleId,
        name: f.ruleId.replace(/[^A-Za-z0-9]/g, '_'),
        shortDescription: { text: f.category === 'dependency' ? 'Vulnerable dependency' : f.title },
        fullDescription: { text: f.description || f.title },
        helpUri: f.advisory?.url,
        properties: { tags: ['security', f.category, f.cwe].filter(Boolean) },
      });
    }
  }
  const level = { critical: 'error', high: 'error', medium: 'warning', low: 'note', info: 'note' };
  return {
    $schema: 'https://json.schemastore.org/sarif-2.1.0.json',
    version: '2.1.0',
    runs: [{
      tool: { driver: { name: 'PandaShield AI (Hackathon Edition)', informationUri: 'https://github.com/', rules: [...rules.values()] } },
      results: (scan.findings || []).map((f) => ({
        ruleId: f.ruleId,
        level: level[f.severity] || 'warning',
        message: { text: f.ai?.explanation || f.description || f.title },
        locations: [{ physicalLocation: { artifactLocation: { uri: f.file }, region: f.line ? { startLine: f.line } : undefined } }],
        partialFingerprints: { pandashieldId: f.id },
        properties: { severity: f.severity, priority: f.ai?.priority, status: f.status },
      })),
    }],
  };
}

function location(f) {
  return f.line ? `${f.file}:${f.line}` : f.file;
}

function describeSource(src) {
  if (!src) return 'n/a';
  if (src.type === 'github') return `GitHub ${src.owner}/${src.repo}${src.ref && src.ref !== 'HEAD' ? `@${src.ref}` : ''}`;
  if (src.type === 'sample') return 'Built-in vulnerable demo app';
  return `Uploaded files (${src.fileCount ?? '?'})`;
}
